#!/usr/bin/env bash
#
# ==============================================================================
#  onboard-project.sh — подготовка автодеплоя для нового репозитория
# ==============================================================================
#
#  НАЗНАЧЕНИЕ
#  ----------
#  Берёт ссылку на GitHub-репозиторий и полностью готовит его к автодеплою
#  на один общий VPS. После запуска любой push/merge в ветку main приводит
#  к автоматическому деплою на сервер через GitHub Actions.
#
#  Скрипт делает ДВЕ части работы:
#    1. СЕРВЕРНАЯ (по SSH на VPS): генерит deploy key репозитория, дописывает
#       ~/.ssh/config, клонирует репозиторий в /opt/<имя>.
#    2. GITHUB (через gh CLI): добавляет deploy key в репо, кладёт secrets,
#       коммитит workflow-файл .github/workflows/deploy.yml.
#
#  МОДЕЛЬ ДОСТУПОВ (важно понимать, что куда идёт)
#  -----------------------------------------------
#  Здесь участвуют ДВА разных SSH-ключа. Не перепутать:
#
#    a) DEPLOY KEY (свой на каждый репо)
#       - живёт на СЕРВЕРЕ (приватная часть), генерится этим скриптом
#       - ПУБЛИЧНАЯ часть добавляется в GitHub → Settings репо → Deploy keys
#       - назначение: сервер делает `git pull` из приватного репо
#       - права: READ-ONLY (без write)
#
#    b) СЛУЖЕБНЫЙ КЛЮЧ ACTIONS→СЕРВЕР (один общий на все репо)
#       - генерится ОДИН раз заранее (см. bootstrap-deploy-server.sh)
#       - ПУБЛИЧНАЯ часть лежит в ~/.ssh/authorized_keys пользователя deploy на VPS
#       - ПРИВАТНАЯ часть кладётся этим скриптом в GitHub Secrets (SSH_PRIVATE_KEY)
#       - назначение: раннер GitHub Actions заходит по SSH на VPS и запускает деплой
#
#    Итого: deploy key (public) → в Deploy keys репо.
#           служебный ключ (private) → в Secrets репо.
#           Деплой-ключ В SECRETS НЕ КЛАДЁТСЯ — это разные вещи.
#
#  .ENV (секреты приложения)
#  -------------------------
#  .env НЕ хранится в git (он в .gitignore). Если передать второй аргумент —
#  путь к локальному .env — его содержимое кладётся в секрет ENV_FILE, а
#  workflow на сервере воссоздаёт из него /opt/<имя>/.env при каждом деплое
#  (права 600, в логи не печатается). Без второго аргумента .env на сервере
#  не трогается.
#
#  КТО ЗАПУСКАЕТ
#  -------------
#  Один человек с admin-правами на репозитории (сейчас — ты, после передачи
#  дел — сменщик). Сотрудники этот скрипт не запускают: они только пушат код
#  под своими аккаунтами. В gh CLI логинится ТОЛЬКО запускающий, один раз.
#
#  ПРЕДВАРИТЕЛЬНЫЕ ТРЕБОВАНИЯ (выполнить ОДИН раз до первого запуска)
#  -----------------------------------------------------------------
#    1. Установлен gh CLI            → https://cli.github.com
#    2. Выполнен вход:  gh auth login
#       ВАЖНО: токену нужен scope `workflow` (иначе GitHub запретит коммитить
#       файлы в .github/workflows/). При входе через браузер он выдаётся.
#       Проверить: gh auth status   (в списке scopes должен быть 'workflow')
#    3. Поднят сервер: есть пользователь `deploy` и служебный ключ в его
#       authorized_keys. Если нет — сначала запусти bootstrap-deploy-server.sh
#    4. На машине, где запускается скрипт, есть приватный служебный ключ
#       (~/.ssh/actions_deploy) — та же пара, чья публичная часть на сервере.
#    5. SSH-доступ с этой машины к серверу под пользователем deploy работает:
#       ssh deploy@<SERVER_IP>   должен пускать без пароля.
#
#  ИСПОЛЬЗОВАНИЕ
#  -------------
#    ./onboard-project.sh <ссылка-или-owner/repo> [путь-к-.env]
#
#    Первый аргумент — репозиторий. Принимает любой из форматов:
#      https://github.com/owner/repo
#      https://github.com/owner/repo.git
#      https://github.com/owner/repo/tree/main
#      git@github.com:owner/repo.git
#      owner/repo
#
#    Второй аргумент (необязательный) — путь к локальному .env-файлу. Если
#    задан, его содержимое загружается в секрет репозитория ENV_FILE, и при
#    каждом деплое workflow воссоздаёт /opt/<имя>/.env на сервере из этого
#    секрета (с правами 600). Если не задан — .env на сервере не трогается
#    (положи его туда вручную, либо он уже есть).
#
#    Примеры:
#      ./onboard-project.sh owner/proj1
#      ./onboard-project.sh owner/proj1 ./secrets/proj1.env
#
#  ИДЕМПОТЕНТНОСТЬ
#  ---------------
#  Скрипт можно запускать повторно на том же репо безопасно: ключи, конфиг,
#  клон, deploy key и workflow не пересоздаются, если уже существуют.
#  Secrets перезаписываются (это ожидаемо — удобно для ротации).
#
#  НАСТРОЙКА: правь блок КОНФИГУРАЦИЯ ниже под своё окружение.
# ==============================================================================

# ------------------------------------------------------------------------------
#  set -euo pipefail — строгий режим bash. Объяснение по флагам:
#    -e            : прервать скрипт при первой же ошибке любой команды
#    -u            : ошибка при обращении к необъявленной переменной (ловит опечатки)
#    -o pipefail   : падение пайпа, если упало ЛЮБОЕ звено, а не только последнее
#  Вместе это гарантирует, что скрипт не продолжит работу в полусломанном
#  состоянии (например, не полезет в GitHub, если сорвался SSH на сервер).
# ------------------------------------------------------------------------------
set -euo pipefail

# ==============================================================================
#  КОНФИГУРАЦИЯ — отредактируй под своё окружение
# ==============================================================================

# Пользователь и хост VPS, под которым делается деплой.
# Это НЕ root — отдельный пользователь deploy с доступом к /opt/* и группе docker.
SERVER_USER="deploy"
SERVER_HOST="1.2.3.4"            # ← IP или домен твоего VPS

# SSH-порт сервера. Если SSH слушает на стандартном порту 22 — оставь пустым,
# секрет SERVER_PORT не будет создан и workflow возьмёт 22 по умолчанию.
# Если порт нестандартный (например, 2222) — укажи здесь.
SERVER_PORT=""                   # ← нестандартный SSH-порт, или "" для 22

# Базовая директория, куда клонируются проекты на сервере.
# Итоговый путь проекта: ${DEPLOY_BASE}/<имя-репо>
DEPLOY_BASE="/opt"

# Приватная часть СЛУЖЕБНОГО ключа (Actions→сервер) на ЭТОЙ машине.
# Его публичная пара уже должна лежать в authorized_keys на сервере.
ACTIONS_KEY="${HOME}/.ssh/actions_deploy"

# Шаблон workflow. Лежит рядом со скриптом. Он универсальный (путь проекта
# вычисляется из имени репо в рантайме), поэтому одинаков для всех репозиториев.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKFLOW_FILE="${SCRIPT_DIR}/deploy.yml"

# Заголовок (title) для deploy key в GitHub — чтобы потом было видно, чей ключ.
DEPLOY_KEY_TITLE="vps-prod-$(date +%Y%m)"

# ==============================================================================
#  ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# ==============================================================================

# Печать с префиксом — чтобы в выводе было видно стадию.
log()  { printf '\033[1;34m[onboard]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------------------------
#  preflight — проверки окружения ДО любых изменений.
#  Лучше упасть здесь с понятным сообщением, чем оставить полунастроенный репо.
# ------------------------------------------------------------------------------
preflight() {
  # Проверяем, что SERVER_HOST заменён с placeholder-значения.
  [[ "${SERVER_HOST}" == "1.2.3.4" ]] \
    && die "Замени SERVER_HOST='1.2.3.4' на реальный IP/домен твоего VPS в начале скрипта."

  # gh установлен?
  command -v gh >/dev/null 2>&1 \
    || die "gh CLI не установлен. Установи: https://cli.github.com"

  # gh авторизован?
  gh auth status >/dev/null 2>&1 \
    || die "gh не авторизован. Выполни: gh auth login"

  # У токена есть scope 'workflow'? Без него коммит в .github/workflows/ упадёт.
  # gh auth status печатает строку со scopes; ищем в ней 'workflow'.
  if ! gh auth status 2>&1 | grep -q "workflow"; then
    warn "У токена gh, похоже, нет scope 'workflow'."
    warn "Коммит workflow-файла может не пройти. Перелогинься: gh auth login"
    warn "и убедись, что выдан scope 'workflow' (gh auth refresh -s workflow)."
  fi

  # Приватный служебный ключ на месте?
  [[ -f "${ACTIONS_KEY}" ]] \
    || die "Не найден служебный ключ ${ACTIONS_KEY}. Сначала bootstrap сервера."

  # Шаблон workflow рядом?
  [[ -f "${WORKFLOW_FILE}" ]] \
    || die "Не найден ${WORKFLOW_FILE}. Положи deploy.yml рядом со скриптом."

  # SSH до сервера работает? BatchMode=yes запрещает интерактивный пароль —
  # если ключ не настроен, команда сразу вернёт ошибку, а не повиснет на вводе.
  local ssh_port_opt=()
  [[ -n "${SERVER_PORT}" ]] && ssh_port_opt=(-p "${SERVER_PORT}")
  ssh -o BatchMode=yes -o ConnectTimeout=10 \
      "${ssh_port_opt[@]}" "${SERVER_USER}@${SERVER_HOST}" "true" 2>/dev/null \
    || die "Нет SSH-доступа к ${SERVER_USER}@${SERVER_HOST}${SERVER_PORT:+:${SERVER_PORT}}. Проверь ключ/хост/порт."
}

# ------------------------------------------------------------------------------
#  resolve_repo — нормализует ввод в канонический owner/repo.
#  Делегируем разбор самому gh: он принимает url/owner-repo, проверяет, что
#  репо существует и доступен под текущим аккаунтом, и возвращает nameWithOwner.
#  Это надёжнее регэкспа: ловит опечатки и проблемы с правами в первой же строке.
# ------------------------------------------------------------------------------
resolve_repo() {
  local raw="$1"
  gh repo view "${raw}" --json nameWithOwner -q .nameWithOwner 2>/dev/null \
    || die "Репозиторий не найден или нет доступа: ${raw}"
}

# ==============================================================================
#  ОСНОВНОЙ СЦЕНАРИЙ
# ==============================================================================

main() {
  # --- Аргументы -------------------------------------------------------------
  # ${1:?...} — если первый аргумент не передан, bash сам прервёт скрипт
  # с этим сообщением (работает благодаря set -u).
  local raw="${1:?Использование: ./onboard-project.sh <github-url | owner/repo> [путь-к-.env]}"
  # Второй аргумент необязателен: путь к локальному .env. ${2:-} = пустая
  # строка, если не передан (без падения по set -u).
  local env_path="${2:-}"

  # Если путь к .env передан — проверим, что файл реально существует, ДО работы.
  if [[ -n "${env_path}" && ! -f "${env_path}" ]]; then
    die "Указан .env, но файл не найден: ${env_path}"
  fi

  preflight

  # Канонический owner/repo и короткое имя репозитория.
  local repo name
  repo="$(resolve_repo "${raw}")"   # например: bbooster/proj1
  name="${repo##*/}"                # отрезаем всё до последнего '/': proj1

  local project_path="${DEPLOY_BASE}/${name}"

  log "Репозиторий : ${repo}"
  log "Имя проекта : ${name}"
  log "Путь на VPS : ${project_path}"
  log "Сервер      : ${SERVER_USER}@${SERVER_HOST}"
  echo

  # ==========================================================================
  #  ЧАСТЬ 1. СЕРВЕР: deploy key + ssh config
  # ==========================================================================
  # Запускаем блок команд на сервере одним SSH-вызовом (heredoc <<EOF).
  # Переменные $name подставляются ЛОКАЛЬНО до отправки (heredoc без кавычек),
  # поэтому на сервер уходит уже готовый текст с именем проекта.
  log "[1/5] Сервер: генерация deploy key и настройка ~/.ssh/config…"
  ssh "${ssh_port_opt[@]}" "${SERVER_USER}@${SERVER_HOST}" bash -s <<EOF
set -euo pipefail
cd ~/.ssh

# Генерируем deploy key репозитория, если его ещё нет (идемпотентно).
# ed25519 — современный короткий ключ; -N "" — без passphrase (деплой
# неинтерактивный, ключ и так лежит только на сервере под deploy).
if [[ ! -f "deploy_${name}" ]]; then
  ssh-keygen -t ed25519 -f "deploy_${name}" -N "" -C "deploy@${name}"
fi

# Дописываем алиас в ~/.ssh/config, если его ещё нет.
# Алиас github-<name> заставляет git использовать ИМЕННО этот deploy key
# для этого репо (IdentitiesOnly yes исключает перебор других ключей).
if ! grep -q "Host github-${name}\$" config 2>/dev/null; then
  cat >> config <<CFG

Host github-${name}
    HostName github.com
    User git
    IdentityFile ~/.ssh/deploy_${name}
    IdentitiesOnly yes
CFG
fi
chmod 600 config
EOF

  # Забираем ПУБЛИЧНУЮ часть deploy key с сервера, чтобы передать её в GitHub.
  log "[2/5] Забираю публичный deploy key с сервера…"
  local deploy_pub
  deploy_pub="$(ssh "${ssh_port_opt[@]}" "${SERVER_USER}@${SERVER_HOST}" "cat ~/.ssh/deploy_${name}.pub")"

  # ==========================================================================
  #  ЧАСТЬ 2. GITHUB: deploy key (read-only)
  # ==========================================================================
  # gh repo deploy-key add принимает ФАЙЛ с публичным ключом — пишем во
  # временный файл. БЕЗ --allow-write: серверу нужен только pull, не push.
  log "[3/5] GitHub: добавляю deploy key (read-only)…"
  local tmp_pub
  tmp_pub="$(mktemp)"
  printf '%s\n' "${deploy_pub}" > "${tmp_pub}"

  if gh repo deploy-key add "${tmp_pub}" \
        --title "${DEPLOY_KEY_TITLE}" --repo "${repo}" >/dev/null 2>&1; then
    log "      deploy key добавлен"
  else
    # Чаще всего ошибка = ключ уже добавлен ранее (повторный запуск). Не падаем.
    warn "      deploy key не добавлен (вероятно, уже существует) — пропускаю"
  fi
  rm -f "${tmp_pub}"

  # ==========================================================================
  #  ЧАСТЬ 3. СЕРВЕР: клонирование репозитория
  # ==========================================================================
  # Клонируем через АЛИАС github-<name> (а не github.com), чтобы git взял
  # нужный deploy key. Клон делаем только если папки ещё нет (идемпотентно).
  log "[4/5] Сервер: клонирование в ${project_path}…"
  ssh "${ssh_port_opt[@]}" "${SERVER_USER}@${SERVER_HOST}" bash -s <<EOF
set -euo pipefail
if [[ ! -d "${project_path}/.git" ]]; then
  git clone "git@github-${name}:${repo}.git" "${project_path}"
else
  echo "  ${project_path} уже существует — пропускаю клон"
fi
EOF

  # ==========================================================================
  #  ЧАСТЬ 4. GITHUB: secrets
  # ==========================================================================
  # Кладём приватный СЛУЖЕБНЫЙ ключ и параметры подключения.
  # gh шифрует значения публичным ключом репо перед отправкой — открытым
  # текстом по сети ничего не передаётся. Повторный set просто перезапишет
  # значение (это удобно для ротации ключа).
  log "[5/5] GitHub: установка secrets…"
  gh secret set SSH_PRIVATE_KEY < "${ACTIONS_KEY}" --repo "${repo}"
  gh secret set SERVER_HOST --body "${SERVER_HOST}" --repo "${repo}"
  gh secret set SERVER_USER --body "${SERVER_USER}" --repo "${repo}"
  if [[ -n "${SERVER_PORT}" ]]; then
    gh secret set SERVER_PORT --body "${SERVER_PORT}" --repo "${repo}"
    log "      SERVER_PORT=${SERVER_PORT} сохранён в secrets"
  fi

  # .env → секрет ENV_FILE (только если путь передан вторым аргументом).
  # Читаем файл через stdin (< file), чтобы содержимое не светилось в списке
  # процессов (как было бы с --body "$(cat ...)"). Workflow на сервере сам
  # воссоздаст /opt/<имя>/.env из этого секрета при деплое.
  if [[ -n "${env_path}" ]]; then
    gh secret set ENV_FILE < "${env_path}" --repo "${repo}"
    log "      .env загружен в секрет ENV_FILE (${env_path})"
  else
    log "      .env не передан — секрет ENV_FILE не трогаю (на сервере оставь .env вручную)"
  fi

  # ==========================================================================
  #  ЧАСТЬ 5. GITHUB: workflow-файл
  # ==========================================================================
  # Workflow коммитится через Contents API. content ДОЛЖЕН быть в base64
  # (-w0 = без переносов строк, иначе API отвергнет). Если файл уже есть —
  # GitHub требует его текущий sha для обновления; добавляем sha условно,
  # чтобы и создание (sha пустой), и обновление (sha задан) работали.
  log "      GitHub: коммит .github/workflows/deploy.yml…"
  local content sha
  content="$(base64 -w0 "${WORKFLOW_FILE}")"

  # Текущий sha файла, если он уже существует (иначе пустая строка).
  sha="$(gh api "repos/${repo}/contents/.github/workflows/deploy.yml" \
            -q .sha 2>/dev/null || true)"

  # ${sha:+...} раскрывается только если sha НЕ пустой → на новом репо
  # аргумент -f sha=... опускается, на существующем — подставляется.
  gh api "repos/${repo}/contents/.github/workflows/deploy.yml" \
    -X PUT \
    -f message="ci: add/update autodeploy workflow" \
    -f content="${content}" \
    ${sha:+-f sha="${sha}"} >/dev/null

  echo
  log "ГОТОВО ✓  ${repo} задеплоится на ${SERVER_HOST} при следующем push в main."
  log "Проверь первый прогон во вкладке Actions репозитория после push."
}

# Запуск. "$@" пробрасывает все аргументы командной строки в main.
main "$@"
